function uniqueProverbs(list) {
  const seen = new Set();
  const out = [];
  for (const raw of list) {
    let t = String(raw || '').trim();
    if (!t) continue;
    if (!/[.!?…]$/.test(t)) t += '.';
    // нормализация для дедупа
    const key = t
      .toLowerCase()
      .replace(/ё/g, 'е')
      .replace(/[—–−]/g, '-')
      .replace(/\s+/g, ' ')
      .replace(/[«»"']/g, '')
      .replace(/[!?.,;:]+$/g, '');
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(t);
  }
  return out;
}

function loadBank(code) {
  const key = 'window.QUOTE_BANK=';
  const start = code.indexOf(key);
  if (start < 0) throw new Error('QUOTE_BANK not found');
  const i = start + key.length;
  let depth = 0, end = -1;
  for (let p = i; p < code.length; p++) {
    const c = code[p];
    if (c === '[') depth++;
    else if (c === ']') {
      depth--;
      if (depth === 0) {
        end = p;
        break;
      }
    }
  }
  if (end < 0) throw new Error('QUOTE_BANK end not found');
  const bank = Function('return ' + code.slice(i, end + 1))();
  return { bank, start, end, i };
}

