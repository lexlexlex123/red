function quoteCatOf(author) {
  const a = String(author || '').trim();
  if (AUTHOR_CAT[a]) return AUTHOR_CAT[a];
  if (/пословиц|мудрость|афоризм|правило|изречение|максима/i.test(a)) return 'proverbs';
  return 'other';
}

